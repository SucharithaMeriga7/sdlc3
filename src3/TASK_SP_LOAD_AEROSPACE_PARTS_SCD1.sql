    -- Stage: incremental + deduplicated + transformed + filtered
    CREATE OR REPLACE TEMPORARY TABLE STAGE_AEROSPACE_PARTS AS
    WITH INCREMENTAL AS (
        SELECT *
          FROM AEROSPACE_PARTS_SOURCE
         WHERE UPDATED_AT > :v_last_run_ts
    ),
    DEDUPED AS (
        SELECT *
          FROM (
            SELECT *,
                   ROW_NUMBER() OVER (PARTITION BY PART_NUMBER ORDER BY UPDATED_AT DESC) AS RN
              FROM INCREMENTAL
          )
         WHERE RN = 1
    ),
    TRANSFORMED AS (
        SELECT
            PART_NUMBER,
            INITCAP(MANUFACTURER)                                        AS MANUFACTURER,
            CASE WHEN WEIGHT_KG <= 0 THEN NULL ELSE WEIGHT_KG END        AS WEIGHT_KG,
            ROUND(UNIT_PRICE_USD, 2)                                     AS UNIT_PRICE_USD,
            LIFECYCLE_STATUS,
            INSTALLATION_DATE,
            CERTIFICATION_STATUS,
            LEAD_TIME_DAYS,
            UPDATED_AT
          FROM DEDUPED
    ),
    FILTERED AS (
        SELECT *
          FROM TRANSFORMED
         WHERE NOT (
               LIFECYCLE_STATUS = 'End of Life'
           AND INSTALLATION_DATE < DATEADD(YEAR, -3, CURRENT_DATE)
         )
    )
    SELECT
        PART_NUMBER,
        MANUFACTURER,
        WEIGHT_KG,
        UNIT_PRICE_USD,
        LIFECYCLE_STATUS,
        INSTALLATION_DATE,
        CERTIFICATION_STATUS,
        LEAD_TIME_DAYS,
        UPDATED_AT,
        CASE
            WHEN CERTIFICATION_STATUS = 'Pending' AND LEAD_TIME_DAYS > 90
                THEN 'High Risk'
            WHEN CERTIFICATION_STATUS = 'Pending' OR LEAD_TIME_DAYS > 120
                THEN 'Medium Risk'
            WHEN CERTIFICATION_STATUS IN ('FAA','EASA','Dual') AND LEAD_TIME_DAYS <= 60
                THEN 'Low Risk'
            ELSE 'Medium Risk'
        END AS RISK_SCORE
      FROM FILTERED;

    SELECT COUNT(*) INTO v_source_count FROM STAGE_AEROSPACE_PARTS;

