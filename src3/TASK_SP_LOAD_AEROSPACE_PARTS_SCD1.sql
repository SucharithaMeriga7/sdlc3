            PART_NUMBER, MANUFACTURER, WEIGHT_KG, UNIT_PRICE_USD,
            LIFECYCLE_STATUS, INSTALLATION_DATE, CERTIFICATION_STATUS,
            LEAD_TIME_DAYS, UPDATED_AT, RISK_SCORE, ETL_LOAD_TIMESTAMP,
            DECOMMISSION_TIMESTAMP
