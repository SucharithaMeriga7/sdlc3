    v_target_after        NUMBER DEFAULT 0;
    v_insert_count        NUMBER DEFAULT 0;
    v_update_count        NUMBER DEFAULT 0;
    v_soft_delete_count   NUMBER DEFAULT 0;
    v_status              VARCHAR DEFAULT 'SUCCESS';
BEGIN
    v_run_id := 'RUN_' || TO_VARCHAR(CURRENT_TIMESTAMP, 'YYYYMMDD_HH24MISS');
    v_run_ts := CURRENT_TIMESTAMP::TIMESTAMP_NTZ;

    -- Last successful run timestamp
    -- SECTION 2: Source Processing
SELECT -- SECTION 3: Data Validation
COALESCE(MAX(RUN_TIMESTAMP), '1900-01-01'::TIMESTAMP_NTZ)
