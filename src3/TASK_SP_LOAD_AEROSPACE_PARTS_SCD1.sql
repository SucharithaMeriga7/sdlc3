     WHERE T.LIFECYCLE_STATUS <> 'Decommissioned'
       AND NOT EXISTS (
           SELECT 1 FROM AEROSPACE_PARTS_SOURCE S
            WHERE S.PART_NUMBER = T.PART_NUMBER
       );

    v_soft_delete_count := SQLROWCOUNT;

    -- SECTION 5: Reconciliation
INSERT INTO ETL_RECONCILIATION_LOG
        (RUN_ID, RUN_TIMESTAMP, SOURCE_COUNT, TARGET_COUNT_BEFORE,
         TARGET_COUNT_AFTER, INSERT_COUNT, UPDATE_COUNT, SOFT_DELETE_COUNT,
         RUN_STATUS, LAST_UPDATED_AT)
    VALUES
        (:v_run_id, :v_run_ts, :v_source_count, :v_target_before,
         :v_target_after, :v_insert_count, :v_update_count, :v_soft_delete_count,
         :v_status, CURRENT_TIMESTAMP::TIMESTAMP_NTZ);

    RETURN 'SP_LOAD_AEROSPACE_PARTS_SCD1 completed. RUN_ID=' || v_run_id
        || ' INSERTS=' || v_insert_count
        || ' UPDATES=' || v_update_count
        || ' SOFT_DELETES=' || v_soft_delete_count;

