RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
    -- SECTION 1: Variables
    v_start_ts        TIMESTAMP_NTZ := CURRENT_TIMESTAMP();
    v_src_count       INTEGER := 0;
    v_dedup_count     INTEGER := 0;
    v_insert_count    INTEGER := 0;
    v_update_count    INTEGER := 0;
    v_invalid_count   INTEGER := 0;
    v_last_load_ts    TIMESTAMP_NTZ;
    v_result          VARCHAR;

BEGIN
    USE WAREHOUSE SNOWFLAKE_LEARNING_WH;

    -- SECTION 2: Source Processing
    -- Watermark from last successful run
    SELECT COALESCE(MAX(LOAD_TIMESTAMP), '1900-01-01'::TIMESTAMP_NTZ)
    INTO :v_last_load_ts
    FROM GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_TARGET;

    -- Stage incremental raw records
    CREATE OR REPLACE TEMPORARY TABLE SDLC_WIZARD.STG_PARTS_RAW AS
    SELECT
        PART_ID, PART_NUMBER, PART_NAME, PART_DESCRIPTION,
        MANUFACTURER, MANUFACTURER_CODE, CATEGORY,
        UNIT_OF_MEASURE, ROUND(UNIT_PRICE_USD, 3)          AS UNIT_PRICE_USD,
        CASE WHEN WEIGHT_KG <= 0 THEN NULL ELSE WEIGHT_KG END AS WEIGHT_KG,
        CRITICALITY_LEVEL, HAZMAT_FLAG, CAGE_CODE,
        NSN_NUMBER, LEAD_TIME_DAYS, MIN_ORDER_QTY,
        STOCK_QUANTITY, REORDER_POINT, SUPPLIER_ID,
        COUNTRY_OF_ORIGIN, COMPLIANCE_STATUS,
        CERTIFICATION_STATUS, LIFECYCLE_STATUS,
        INSTALLATION_DATE, UPDATED_AT,
        UPPER(MANUFACTURER)                                AS MANUFACTURER_CLEAN,
        CASE
            WHEN CERTIFICATION_STATUS = 'Pending' AND LEAD_TIME_DAYS > 90  THEN 'High Risk'
            WHEN CERTIFICATION_STATUS IN ('FAA','EASA','Dual') AND LEAD_TIME_DAYS <= 60 THEN 'Low Risk'
            ELSE 'Medium Risk'
        END AS RISK_SCORE
    FROM GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_SOURCE
    WHERE UPDATED_AT > :v_last_load_ts;

    SELECT COUNT(*) INTO :v_src_count FROM SDLC_WIZARD.STG_PARTS_RAW;

    -- SECTION 3: Data Validation
    -- Exclude End-of-Life records older than 2 years
    CREATE OR REPLACE TEMPORARY TABLE SDLC_WIZARD.STG_PARTS_INVALID AS
    SELECT * FROM SDLC_WIZARD.STG_PARTS_RAW
    WHERE LIFECYCLE_STATUS = 'End of Life'
      AND INSTALLATION_DATE < DATEADD(year, -2, CURRENT_DATE);

    SELECT COUNT(*) INTO :v_invalid_count FROM SDLC_WIZARD.STG_PARTS_INVALID;

    -- Deduplicate: keep latest UPDATED_AT per PART_NUMBER
    CREATE OR REPLACE TEMPORARY TABLE SDLC_WIZARD.STG_PARTS_DEDUP AS
    SELECT * FROM (
        SELECT *,
               ROW_NUMBER() OVER (PARTITION BY PART_NUMBER ORDER BY UPDATED_AT DESC) AS RN
        FROM SDLC_WIZARD.STG_PARTS_RAW
        WHERE NOT (LIFECYCLE_STATUS = 'End of Life'
                   AND INSTALLATION_DATE < DATEADD(year, -2, CURRENT_DATE))
    ) WHERE RN = 1;

    SELECT COUNT(*) INTO :v_dedup_count FROM SDLC_WIZARD.STG_PARTS_DEDUP;

    -- SECTION 4: Merge Logic
    -- SCD1 MERGE + soft-delete for missing source records
    MERGE INTO GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_TARGET T
    USING SDLC_WIZARD.STG_PARTS_DEDUP S
    ON T.PART_NUMBER = S.PART_NUMBER
    WHEN MATCHED THEN UPDATE SET
        T.PART_ID              = S.PART_ID,
        T.PART_NAME            = S.PART_NAME,
        T.PART_DESCRIPTION     = S.PART_DESCRIPTION,
        T.MANUFACTURER         = S.MANUFACTURER_CLEAN,
        T.MANUFACTURER_CODE    = S.MANUFACTURER_CODE,
        T.CATEGORY             = S.CATEGORY,
        T.UNIT_OF_MEASURE      = S.UNIT_OF_MEASURE,
        T.UNIT_PRICE_USD       = S.UNIT_PRICE_USD,
        T.WEIGHT_KG            = S.WEIGHT_KG,
        T.CRITICALITY_LEVEL    = S.CRITICALITY_LEVEL,
        T.HAZMAT_FLAG          = S.HAZMAT_FLAG,
        T.CAGE_CODE            = S.CAGE_CODE,
        T.NSN_NUMBER           = S.NSN_NUMBER,
        T.LEAD_TIME_DAYS       = S.LEAD_TIME_DAYS,
        T.MIN_ORDER_QTY        = S.MIN_ORDER_QTY,
        T.STOCK_QUANTITY       = S.STOCK_QUANTITY,
        T.REORDER_POINT        = S.REORDER_POINT,
        T.SUPPLIER_ID          = S.SUPPLIER_ID,
        T.COUNTRY_OF_ORIGIN    = S.COUNTRY_OF_ORIGIN,
        T.COMPLIANCE_STATUS    = S.COMPLIANCE_STATUS,
        T.CERTIFICATION_STATUS = S.CERTIFICATION_STATUS,
        T.LIFECYCLE_STATUS     = S.LIFECYCLE_STATUS,
        T.INSTALLATION_DATE    = S.INSTALLATION_DATE,
        T.RISK_SCORE           = S.RISK_SCORE,
        T.UPDATED_AT           = S.UPDATED_AT,
        T.LOAD_TIMESTAMP       = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (
        PART_ID, PART_NUMBER, PART_NAME, PART_DESCRIPTION,
        MANUFACTURER, MANUFACTURER_CODE, CATEGORY,
        UNIT_OF_MEASURE, UNIT_PRICE_USD, WEIGHT_KG,
        CRITICALITY_LEVEL, HAZMAT_FLAG, CAGE_CODE,
        NSN_NUMBER, LEAD_TIME_DAYS, MIN_ORDER_QTY,
        STOCK_QUANTITY, REORDER_POINT, SUPPLIER_ID,
        COUNTRY_OF_ORIGIN, COMPLIANCE_STATUS,
        CERTIFICATION_STATUS, LIFECYCLE_STATUS,
        INSTALLATION_DATE, RISK_SCORE, UPDATED_AT, LOAD_TIMESTAMP
    ) VALUES (
        S.PART_ID, S.PART_NUMBER, S.PART_NAME, S.PART_DESCRIPTION,
        S.MANUFACTURER_CLEAN, S.MANUFACTURER_CODE, S.CATEGORY,
        S.UNIT_OF_MEASURE, S.UNIT_PRICE_USD, S.WEIGHT_KG,
        S.CRITICALITY_LEVEL, S.HAZMAT_FLAG, S.CAGE_CODE,
        S.NSN_NUMBER, S.LEAD_TIME_DAYS, S.MIN_ORDER_QTY,
        S.STOCK_QUANTITY, S.REORDER_POINT, S.SUPPLIER_ID,
        S.COUNTRY_OF_ORIGIN, S.COMPLIANCE_STATUS,
        S.CERTIFICATION_STATUS, S.LIFECYCLE_STATUS,
        S.INSTALLATION_DATE, S.RISK_SCORE, S.UPDATED_AT, CURRENT_TIMESTAMP()
    );

    -- Capture insert/update counts
    SELECT COUNT_IF(LOAD_TIMESTAMP >= :v_start_ts AND UPDATED_AT = LOAD_TIMESTAMP) INTO :v_insert_count
    FROM GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_TARGET;

    SET v_update_count = v_dedup_count - v_insert_count;

    -- Soft-delete: mark target records absent from full source as Decommissioned
    UPDATE GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_TARGET T
    SET T.LIFECYCLE_STATUS = 'Decommissioned',
        T.LOAD_TIMESTAMP   = CURRENT_TIMESTAMP()
    WHERE T.LIFECYCLE_STATUS <> 'Decommissioned'
      AND NOT EXISTS (
          SELECT 1 FROM GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.AEROSPACE_PARTS_SOURCE S
          WHERE S.PART_NUMBER = T.PART_NUMBER
      );

    -- SECTION 5: Reconciliation
    -- Log run metrics to ETL_RECONCILIATION_LOG
    INSERT INTO GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.ETL_RECONCILIATION_LOG (
        PIPELINE_NAME, RUN_START_TS, RUN_END_TS,
        SOURCE_COUNT, INVALID_COUNT, DEDUP_COUNT,
        INSERT_COUNT, UPDATE_COUNT, STATUS, NOTES
    ) VALUES (
        'SP_LOAD_AEROSPACE_PARTS_SCD1',
        :v_start_ts,
        CURRENT_TIMESTAMP(),
        :v_src_count,
        :v_invalid_count,
        :v_dedup_count,
        :v_insert_count,
        :v_update_count,
        'SUCCESS',
        'Watermark: ' || :v_last_load_ts::VARCHAR
    );

    -- SECTION 6: Error Handling
    v_result := OBJECT_CONSTRUCT(
        'status',        'SUCCESS',
        'src_count',     :v_src_count,
        'invalid_count', :v_invalid_count,
        'dedup_count',   :v_dedup_count,
        'insert_count',  :v_insert_count,
        'update_count',  :v_update_count,
        'run_start',     :v_start_ts::VARCHAR,
        'run_end',       CURRENT_TIMESTAMP()::VARCHAR
    )::VARCHAR;

    RETURN v_result;

EXCEPTION WHEN OTHER THEN
    INSERT INTO GEN_AI_POC_SNOWFLAKECOE.SDLC_WIZARD.ETL_RECONCILIATION_LOG (
        PIPELINE_NAME, RUN_START_TS, RUN_END_TS,
        SOURCE_COUNT, INVALID_COUNT, DEDUP_COUNT,
        INSERT_COUNT, UPDATE_COUNT, STATUS, NOTES
    ) VALUES (
        'SP_LOAD_AEROSPACE_PARTS_SCD1',
        :v_start_ts, CURRENT_TIMESTAMP(),
        :v_src_count, :v_invalid_count, :v_dedup_count,
        :v_insert_count, :v_update_count,
        'FAILED', SQLERRM
    );
    RETURN OBJECT_CONSTRUCT('error', SQLERRM)::VARCHAR;
END;
$$;