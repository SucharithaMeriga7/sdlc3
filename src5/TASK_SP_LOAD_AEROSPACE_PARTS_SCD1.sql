            WHEN INSTALLATION_DATE IS NOT NULL
             AND DATEDIFF('year', INSTALLATION_DATE::DATE, CURRENT_DATE()) >= 2
            THEN NULL
            ELSE WEIGHT_KG
        END                                                         AS WEIGHT_KG,
        CASE
            WHEN UPPER(TRIM(CERTIFICATION_STATUS)) = 'NOT_CERTIFIED'
                THEN 3
            WHEN UPPER(TRIM(CERTIFICATION_STATUS)) = 'PENDING'
             AND LEAD_TIME_DAYS > 30
                THEN 2
            WHEN UPPER(TRIM(CERTIFICATION_STATUS)) = 'CERTIFIED'
             AND LEAD_TIME_DAYS <= 30
