        SRC.LIFECYCLE_STATUS,
        CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
        SRC.MANUFACTURER,
        SRC.PART_NAME,
        SRC.PART_NUMBER,
